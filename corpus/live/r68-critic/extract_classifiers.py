#!/usr/bin/env python3
"""Extract classify_process + classify_streams VERBATIM from the tracked
run_battery.py via ast source segments; write them to verbatim_classifiers.py.
No re-implementation — the measured code is the committed code."""
import ast
import hashlib
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "corpus" / "fixtures" / "run_battery.py"
OUT = Path(__file__).resolve().parent / "verbatim_classifiers.py"

tree = ast.parse(SRC.read_text())
wanted = {"classify_process", "classify_streams"}
found = {}
for node in ast.walk(tree):
    if isinstance(node, ast.FunctionDef) and node.name in wanted and node.name not in found:
        seg = ast.get_source_segment(SRC.read_text(), node)
        found[node.name] = textwrap.dedent(seg)

missing = wanted - set(found)
if missing:
    sys.exit(f"missing functions: {missing}")

header = [
    "# generated by extract_classifiers.py — verbatim ast.get_source_segment",
    f"# source: {SRC}",
]
body = []
for name in sorted(found):
    seg = found[name]
    digest = hashlib.sha256(seg.encode()).hexdigest()
    header.append(f"# {name} sha256:{digest}")
    body.append(seg)

OUT.write_text("\n".join(header) + "\n\n\n" + "\n\n\n".join(body) + "\n")
print(f"wrote {OUT}")
for name in sorted(found):
    print(f"{name} sha256:{hashlib.sha256(found[name].encode()).hexdigest()}")
