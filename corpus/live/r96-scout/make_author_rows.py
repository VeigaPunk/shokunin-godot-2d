#!/usr/bin/env python3
"""r96-scout author-row builder — emits author-rows.py.txt from the canonical receipts.

Each cell's PASS line is taken verbatim from runs/r96_<cell>.rep1.out (byte-stable
over all canonical + loadtest reps, asserted here).  ROWS = full lines;
ROWS_PREFIX = same rows except the census stops before its SceneState method list
(the one pure engine-surface block the other twelve cells already exercise).
EXPECTED_ERRORS carries the exact allowlisted ERROR: lines measured for the two
cells that intentionally provoke refusals (ownership, refuse).
"""
import pathlib
import re

HERE = pathlib.Path(__file__).parent
RUNS = HERE / "runs"
LT = RUNS / "loadtest"

CELLS = ["census", "pack_basic", "ownership", "formats", "det", "uid", "takeover",
         "cache", "subres", "extres", "editstate", "refuse", "edges"]
SCRIPT = "scene_io_lattice.gd"

EXPECTED_ERRORS = {
    "r96_scene_io_ownership": (
        'ERROR: Invalid owner. Owner must be an ancestor in the tree.',
        'ERROR: Condition "p_owner == this" is true.',
    ),
    "r96_scene_io_refuse": (
        "ERROR: Cannot save file 'user://r96_absent_dir_xyz/deep/x.tscn'.",
        "ERROR: Can't save empty resource to path 'user://r96/null.tscn'.",
        "ERROR: Can't save resource to empty path. Provide non-empty path or a Resource with non-empty resource_path.",
        "ERROR: Cannot open file 'user://r96/nope.tscn'.",
        "ERROR: Failed loading resource: user://r96/nope.tscn.",
        "ERROR: Error loading resource: 'user://r96/nope.tscn'.",
        "ERROR: Resource file not found: user://r96 (expected type: unknown)",
        "ERROR: Error loading resource: 'user://r96'.",
        "ERROR: Resource file not found: res:// (expected type: unknown)",
        "ERROR: Error loading resource: ''.",
        'ERROR: Parameter "p_scene" is null.',
        'ERROR: Failed to instantiate scene state of "", node count is 0. Make sure the PackedScene resource is valid.',
        "ERROR: Another resource is loaded from path 'user://r96/collide.tres' (possible cyclic resource inclusion).",
    ),
}


def pass_line(cell, path):
    for line in path.read_text().splitlines():
        if line.startswith("PASS scene_io_lattice %s " % cell):
            return line
    raise SystemExit("no PASS line for %s in %s" % (cell, path))


rows = []
prefix_rows = []
stability = {}
for cell in CELLS:
    canon = sorted(RUNS.glob(f"r96_{cell}.rep*.out"))
    load = sorted(LT.glob(f"{cell}.rep*.out"))
    lines = {pass_line(cell, p) for p in canon}
    load_lines = {pass_line(cell, p) for p in load}
    if len(lines) != 1 or len(load_lines) != 1 or lines != load_lines:
        raise SystemExit(f"cell {cell} is not byte-stable: canon={len(lines)} load={len(load_lines)}")
    line = lines.pop()
    stability[cell] = (len(canon), len(load))
    case = "r96_scene_io_" + cell
    rows.append((case, SCRIPT, ["--arm=%s" % cell], 0, line))
    if cell == "census":
        cut = line.find(" ss_methods=")
        assert cut > 0
        prefix_rows.append((case, SCRIPT, ["--arm=%s" % cell], 0, line[:cut]))
    else:
        prefix_rows.append((case, SCRIPT, ["--arm=%s" % cell], 0, line))

out = [
    "# r96-scout author rows — PackedScene/ResourceSaver/ResourceLoader round-trip lattice.",
    "# Generated by make_author_rows.py from corpus/live/r96-scout/runs/ (canonical 3/6 reps",
    "# + loadtest 3 reps under load avg 94–148, all byte-identical per cell).",
    "# Script: corpus/fixtures/scene_io_lattice.gd (self-contained SceneTree, --arm= convention).",
    "#",
    "# ROWS = full-line signatures (all 13 cells byte-stable on every receipt).",
    "# ROWS_PREFIX = same, except r96_scene_io_census stops before its SceneState method",
    "#   list (the one engine-surface block the other twelve cells already exercise).",
    "",
    "ROWS = [",
]
for case, script, flags, exit_code, sig in rows:
    out.append("    (%r, %r, %r, %d," % (case, script, flags, exit_code))
    out.append("     %r)," % sig)
out.append("]")
out.append("")
out.append("# Prefix form: identical except the census row stops before `ss_methods=`.")
out.append("ROWS_PREFIX = [")
for case, script, flags, exit_code, sig in prefix_rows:
    out.append("    (%r, %r, %r, %d," % (case, script, flags, exit_code))
    out.append("     %r)," % sig)
out.append("]")
out.append("")
out.append("EXPECTED_ERRORS = {")
for case, errs in EXPECTED_ERRORS.items():
    out.append("    %r: (" % case)
    for e in errs:
        out.append("        %r," % e)
    out.append("    ),")
out.append("}")
out.append("")

(HERE / "author-rows.py.txt").write_text("\n".join(out))
print("cells:", len(rows), "stability(canon,load):", stability)
print("sig lengths:", {c: len(s) for c, s in ((r[0], r[4]) for r in rows)})
print("wrote author-rows.py.txt")
