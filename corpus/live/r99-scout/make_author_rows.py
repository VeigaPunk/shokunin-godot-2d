#!/usr/bin/env python3
"""r99-scout author-row builder — 16 verbatim CASES rows for the headless in-engine
audio lattice (prefix r99_).

Row shape matches corpus/fixtures/run_battery.py CASES:
    (case, script, flags, expected_exit, signature)

- ROWS:        full PASS line for the 8 byte-stable cells (out_uniq==1 over all
               canonical+loadtest receipts); the stable prefix for the 8 cells whose
               tail carries wall-clock block counters.
- ROWS_PREFIX: the stable prefix (PASS line cut at ' | ') for every cell — the
               recommended gating form.
- EXPECTED_ERRORS: one entry, `r99_audio_gen` = the two refused `clear_buffer()`
               ERROR lines (exact text, deterministic on all 9 receipts).

Probe file lands at corpus/fixtures/audio_lattice.gd.

Output: author-rows.py.txt
"""
import pathlib

HERE = pathlib.Path(__file__).parent
RUNS = HERE / "runs"

CELLS = ["census", "bus", "autoplay", "stoppos", "peak_calib", "mixblock", "advance",
         "finish", "loop_degenerate", "loop_pts", "gen", "gen_peak", "poly",
         "bus_peak", "p2d", "pan_law", "gen2d", "pause"]


def pass_line(cell, rep):
    text = (RUNS / f"r99_{cell}.rep{rep}.out").read_text()
    for line in text.splitlines():
        if line.startswith("PASS r99_audio "):
            return line
    raise SystemExit(f"no PASS line for {cell} rep{rep}")


def all_outputs(cell):
    outs = [p.read_text() for p in sorted(RUNS.glob(f"r99_{cell}.rep*.out"))]
    lt = RUNS / "loadtest"
    if lt.exists():
        outs += [p.read_text() for p in sorted(lt.glob(f"{cell}.rep*.out"))]
    return outs


def stable_full(cell):
    return len(set(all_outputs(cell))) == 1


rows = []
prefix_rows = []
for cell in CELLS:
    case = f"r99_audio_{cell}"
    line = pass_line(cell, 1)
    prefix = line.split(" | ")[0]
    rows.append((case, "audio_lattice.gd", [f"--arm={cell}"], 0,
                 line if stable_full(cell) else prefix))
    prefix_rows.append((case, "audio_lattice.gd", [f"--arm={cell}"], 0, prefix))

expected_errors = {
    "r99_audio_gen": ('ERROR: Condition "active" is true.',),
}

out = HERE / "author-rows.py.txt"
with out.open("w") as fh:
    fh.write("# r99-scout author rows — headless in-engine audio lattice (prefix r99_)\n")
    fh.write("# Generated by make_author_rows.py from the canonical receipts; verify with verify_rows.py.\n")
    fh.write("# Probe: corpus/fixtures/audio_lattice.gd  Launch: godot --headless --path <proj> --script res://audio_lattice.gd -- --arm=<cell>\n\n")
    fh.write("ROWS = [\n")
    for r in rows:
        fh.write("    (%r, %r, %r, %d,\n     %r),\n" % r)
    fh.write("]\n\nROWS_PREFIX = [\n")
    for r in prefix_rows:
        fh.write("    (%r, %r, %r, %d,\n     %r),\n" % r)
    fh.write("]\n\nEXPECTED_ERRORS = {\n")
    for k, v in expected_errors.items():
        fh.write("    %r: %r,\n" % (k, v))
    fh.write("}\n")

print(f"ROWS={len(rows)} ROWS_PREFIX={len(prefix_rows)} EXPECTED_ERRORS={len(expected_errors)}")
print(f"full-line cells: {[c for c in CELLS if stable_full(c)]}")
print(f"prefix-only cells: {[c for c in CELLS if not stable_full(c)]}")
