#!/usr/bin/env python3
"""r92-scout row builder — turns the canonical receipts into battery-shaped rows.

Writes `author-rows.py.txt`:
  ROWS          — 13 full-line 5-tuples (the recommended gating form; every cell
                  is byte-stable over 3-6 canonical reps AND under load avg 118)
  ROWS_PREFIX   — the same rows with the census tail (`class_method_counts=`) cut,
                  the only engine-version-sensitive field in the set
  EXPECTED_ERRORS — the per-case allowlist, extracted verbatim from the receipts
"""
import collections
import pathlib
import re

HERE = pathlib.Path(__file__).parent
RUNS = HERE / "runs"
CELLS = [
    ("r92_tilemap_census", "census"),
    ("r92_tilemap_atlas", "atlas"),
    ("r92_tilemap_cells", "cells"),
    ("r92_tilemap_custom", "custom"),
    ("r92_tilemap_terrain", "terrain"),
    ("r92_tilemap_pattern", "pattern"),
    ("r92_tilemap_encoding", "encoding"),
    ("r92_tilemap_fixinvalid", "fixinvalid"),
    ("r92_tilemap_srcids", "srcids"),
    ("r92_tilemap_physics", "physics"),
    ("r92_tilemap_timing", "timing"),
    ("r92_tilemap_quadrant", "quadrant"),
    ("r92_tilemap_nav", "nav"),
]
# the only field whose value is an engine-build constant rather than a runtime
# measurement: cut it in the prefix form
CENSUS_TAIL = " class_method_counts="

rows = []
rows_prefix = []
expected = {}
for case, arm in CELLS:
    out = sorted(RUNS.glob(f"r92_tm_{arm}.rep*.out"))[0]
    line = re.search(r"^PASS tilemap_lattice .*$", out.read_text(), re.M).group(0)
    rows.append((case, "tilemap_lattice.gd", [f"--arm={arm}"], 0, line))
    if arm == "census":
        cut = line.index(CENSUS_TAIL)
        rows_prefix.append((case, "tilemap_lattice.gd", [f"--arm={arm}"], 0, line[:cut]))
    else:
        rows_prefix.append((case, "tilemap_lattice.gd", [f"--arm={arm}"], 0, line))
    errs = collections.Counter()
    for err in sorted(RUNS.glob(f"r92_tm_{arm}.rep*.err")) + \
               sorted((RUNS / "loadtest").glob(f"r92_tm_{arm}.rep1.err")):
        for raw in err.read_text().splitlines():
            if "ERROR:" in raw:
                errs[raw.strip()] += 1
    expected[case] = tuple(sorted(errs))

body = ["# r92-scout author rows — TileMapLayer/TileSet authorability lattice.",
        "# Generated by make_author_rows.py from corpus/live/r92-scout/runs/.",
        "# Script: corpus/fixtures/tilemap_lattice.gd",
        "",
        "ROWS = ["]
for case, script, flags, code, sig in rows:
    body.append(f"    ({case!r}, {script!r}, {flags!r}, {code}, {sig!r}),")
body.append("]")
body.append("")
body.append("# Prefix form: identical except the census row stops before")
body.append("# `class_method_counts=` (an engine-build constant, not a measurement).")
body.append("ROWS_PREFIX = [")
for case, script, flags, code, sig in rows_prefix:
    body.append(f"    ({case!r}, {script!r}, {flags!r}, {code}, {sig!r}),")
body.append("]")
body.append("")
body.append("EXPECTED_ERRORS = {")
for case, _ in CELLS:
    entries = expected[case]
    if not entries:
        body.append(f"    {case!r}: (),")
    else:
        body.append(f"    {case!r}: (")
        for e in entries:
            body.append(f"        {e!r},")
        body.append("    ),")
body.append("}")
body.append("")

(HERE / "author-rows.py.txt").write_text("\n".join(body))
print(f"wrote {len(rows)} rows; expected_errors keys: "
      f"{sum(1 for c, _ in CELLS if expected[c])} non-empty")
for case, _ in CELLS:
    print(f"  {case}: {len(expected[case])} error line(s)")
